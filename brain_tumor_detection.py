# 8. TEST-ONLY PREDICTION
# ============================================================

def predict_test_set(
    model,
    test_generator
):

    print("\n" + "=" * 70)
    print("PREDICTING TEST SET ONLY")
    print("=" * 70)

    # Make absolutely sure prediction starts from first test image
    test_generator.reset()

    probabilities = model.predict(
        test_generator,
        verbose=1
    )

    predictions = np.argmax(
        probabilities,
        axis=1
    )

    true_labels = test_generator.classes

    return (
        true_labels,
        predictions,
        probabilities
    )


