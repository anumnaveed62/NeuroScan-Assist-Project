def check_dataset():

    print("\n" + "=" * 70)
    print("CHECKING DATASET")
    print("=" * 70)

    if not os.path.exists(TRAIN_DIR):
        raise FileNotFoundError(
            f"\nTraining folder not found:\n{TRAIN_DIR}\n"
        )

