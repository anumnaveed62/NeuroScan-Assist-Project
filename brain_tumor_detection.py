# 5. BUILD CNN MODEL
# ============================================================

def build_model():

    print("\n" + "=" * 70)
    print("BUILDING MODEL (EfficientNetB0 transfer learning)")
    print("=" * 70)

    base_model = EfficientNetB0(
        input_shape=(IMG_SIZE[0], IMG_SIZE[1], 3),
        include_top=False,
        weights="imagenet"
    )
    base_model.trainable = False  # frozen for phase 1

    inputs = layers.Input(shape=(IMG_SIZE[0], IMG_SIZE[1], 3))
    x = base_model(inputs, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dropout(0.3)(x)
    x = layers.Dense(128, activation="relu")(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.4)(x)

    # 4 classes
    outputs = layers.Dense(NUM_CLASSES, activation="softmax")(x)

    model = models.Model(inputs, outputs)

    model.compile(

        optimizer=tf.keras.optimizers.Adam(
            learning_rate=0.0001
        ),

        loss="sparse_categorical_crossentropy",

        metrics=[
            "accuracy"
        ]
    )

    model.summary()

    return model, base_model


# ============================================================
# 6. TRAIN MODEL
# ============================================================

def train_model(
    model,
    base_model,
    train_generator,
    val_generator
):

    print("\n" + "=" * 70)
    print("STARTING TRAINING")
    print("=" * 70)

    # FIX #1: val_generator is now real held-out data from training/
    # (never from testing/), so these callbacks actually have something
    # to monitor -- previously val_loss/val_accuracy did not exist in the
    # logs at all and these callbacks silently did nothing for 30 epochs.
    callbacks = [

        tf.keras.callbacks.EarlyStopping(
            monitor="val_loss",
            patience=6,
            restore_best_weights=True,
            verbose=1
        ),

        tf.keras.callbacks.ReduceLROnPlateau(
            monitor="val_loss",
            factor=0.5,
            patience=3,
            min_lr=1e-7,
            verbose=1
        ),

        tf.keras.callbacks.ModelCheckpoint(
            os.path.join(
                OUTPUT_DIR,
                "best_brain_tumor_model.keras"
            ),

            monitor="val_accuracy",

            save_best_only=True,

            verbose=1
        )
    ]

    # --- Phase 1: train new head only, backbone frozen -----------------
    print("\n=== Phase 1: training classifier head (backbone frozen) ===")
    history1 = model.fit(

        train_generator,

        epochs=HEAD_EPOCHS,

        validation_data=val_generator,

        callbacks=callbacks,

        verbose=1
    )

    # --- Phase 2: unfreeze top backbone layers, fine-tune at low LR ----
    print("\n=== Phase 2: fine-tuning top backbone layers ===")
    base_model.trainable = True
    for layer in base_model.layers[:FINE_TUNE_AT]:
        layer.trainable = False

    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=1e-5),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )

    history2 = model.fit(

        train_generator,

        epochs=HEAD_EPOCHS + FINE_TUNE_EPOCHS,

        initial_epoch=len(history1.epoch),

        validation_data=val_generator,

        callbacks=callbacks,

        verbose=1
    )

    # Merge both phases' histories into one for the training curve plots
    history = history1
    for key in history.history:
        history.history[key] += history2.history.get(key, [])

    return history


