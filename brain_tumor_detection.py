def create_data_generators():

    print("\n" + "=" * 70)
    print("CREATING DATA GENERATORS")
    print("=" * 70)

    # FIX #1: validation_split carves a held-out set OUT OF training/ only.
    # This is what makes val_loss/val_accuracy actually exist during
    # training, so EarlyStopping/ReduceLROnPlateau/ModelCheckpoint (which
    # monitor those metrics) can actually function -- previously they had
    # nothing to monitor and were silently doing nothing all 30 epochs.
    #
    # preprocess_input (EfficientNet's expected preprocessing) replaces the
    # manual rescale=1/255 -- EfficientNet expects its own specific input
    # scaling, not plain 0-1 normalization.
    train_datagen = ImageDataGenerator(
        preprocessing_function=preprocess_input,

        rotation_range=10,

        width_shift_range=0.10,

        height_shift_range=0.10,

        zoom_range=0.10,

        horizontal_flip=True,

        validation_split=VALIDATION_SPLIT
    )

    # NO augmentation for validation or testing -- only EfficientNet's
    # required preprocessing.
    eval_datagen = ImageDataGenerator(
        preprocessing_function=preprocess_input,

        validation_split=VALIDATION_SPLIT
    )

    test_datagen = ImageDataGenerator(
        preprocessing_function=preprocess_input
    )

    train_generator = train_datagen.flow_from_directory(
        TRAIN_DIR,

        target_size=IMG_SIZE,

        batch_size=BATCH_SIZE,

        class_mode="sparse",

        classes=CLASS_NAMES,

        subset="training",

        shuffle=True,

        seed=SEED
    )

    val_generator = eval_datagen.flow_from_directory(
        TRAIN_DIR,

        target_size=IMG_SIZE,

        batch_size=BATCH_SIZE,

        class_mode="sparse",

        classes=CLASS_NAMES,

        subset="validation",

        shuffle=False,

        seed=SEED
    )

    test_generator = test_datagen.flow_from_directory(
        TEST_DIR,

        target_size=IMG_SIZE,

        batch_size=BATCH_SIZE,

        class_mode="sparse",

        classes=CLASS_NAMES,

        shuffle=False
    )

    print("\nClass mapping:")

    print(train_generator.class_indices)

    print("\nTraining samples:",
          train_generator.samples)

    print("Validation samples:",
          val_generator.samples,
          f"({VALIDATION_SPLIT:.0%} of training/, held out from training)")

    print("Testing samples:",
          test_generator.samples)

    return train_generator, val_generator, test_generator


