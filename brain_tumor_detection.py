# 14. MAIN
# ============================================================

def main():

    print("\n")
    print("=" * 70)
    print("BRAIN TUMOR DETECTION - 4 CLASS CNN")
    print("=" * 70)

    print("\nClasses:")

    for i, name in enumerate(
        CLASS_NAMES
    ):

        print(
            f"  {i} = {name}"
        )

    # --------------------------------------------------------
    # Check dataset
    # --------------------------------------------------------

    check_dataset()

    # --------------------------------------------------------
    # Create generators
    # --------------------------------------------------------

    train_generator, val_generator, test_generator = (
        create_data_generators()
    )

    # --------------------------------------------------------
    # Build model
    # --------------------------------------------------------

    model, base_model = build_model()

    # --------------------------------------------------------
    # Train
    # --------------------------------------------------------

    history = train_model(
        model,
        base_model,
        train_generator,
        val_generator
    )

    # --------------------------------------------------------
    # Save curves
    # --------------------------------------------------------

    save_training_curves(
        history
    )

    # --------------------------------------------------------
    # Save final model
    # --------------------------------------------------------

    save_final_model(
        model
    )

    # --------------------------------------------------------
    # TEST SET ONLY
    # --------------------------------------------------------

    true_labels, predictions, probabilities = (
        predict_test_set(
            model,
            test_generator
        )
    )

    # --------------------------------------------------------
