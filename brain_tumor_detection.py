# 12. SAVE TEST PREDICTIONS
# ============================================================

def save_predictions(
    test_generator,
    true_labels,
    predictions,
    probabilities
):

    print("\nSaving test predictions...")

    filenames = test_generator.filenames

    rows = []

    for i in range(
        len(predictions)
    ):

        true_class = CLASS_NAMES[
            true_labels[i]
        ]

        predicted_class = CLASS_NAMES[
            predictions[i]
        ]

        confidence = float(
            probabilities[i][predictions[i]]
        )

        rows.append({

            "image": filenames[i],

            "actual_class": true_class,

            "predicted_class": predicted_class,

            "confidence": confidence,

            "glioma_probability":
                float(probabilities[i][0]),

            "no_tumor_probability":
                float(probabilities[i][1]),

            "pituitary_probability":
                float(probabilities[i][2]),

            "meningioma_probability":
                float(probabilities[i][3])
        })

    df = pd.DataFrame(rows)

    csv_path = os.path.join(
        OUTPUT_DIR,
        "test_predictions.csv"
    )

    df.to_csv(
        csv_path,
        index=False
    )

    print(
        f"Test predictions saved to:\n{csv_path}"
    )


