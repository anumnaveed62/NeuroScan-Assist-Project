    print(TRAIN_DIR)

    print("\nTesting folder:")
    print(TEST_DIR)

    print("\nTraining image counts:")

    train_total = 0

    for class_name in CLASS_NAMES:

        class_path = os.path.join(TRAIN_DIR, class_name)

