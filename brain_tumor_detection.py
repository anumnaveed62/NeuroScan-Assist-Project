# 9. CALCULATE METRICS
# ============================================================

def calculate_metrics(
    true_labels,
    predictions
):

    print("\n" + "=" * 70)
    print("TEST SET PERFORMANCE")
    print("=" * 70)

    # --------------------------------------------------------
    # Accuracy
    # --------------------------------------------------------

    accuracy = accuracy_score(
        true_labels,
        predictions
    )

    # --------------------------------------------------------
    # Precision
    # --------------------------------------------------------

    precision_macro = precision_score(
        true_labels,
        predictions,
        average="macro",
        zero_division=0
    )

    precision_weighted = precision_score(
        true_labels,
        predictions,
        average="weighted",
        zero_division=0
    )

    # --------------------------------------------------------
    # Recall
    # --------------------------------------------------------

    recall_macro = recall_score(
        true_labels,
        predictions,
        average="macro",
        zero_division=0
    )

    recall_weighted = recall_score(
        true_labels,
        predictions,
        average="weighted",
        zero_division=0
    )

    # --------------------------------------------------------
    # F1
    # --------------------------------------------------------

    f1_macro = f1_score(
        true_labels,
        predictions,
        average="macro",
        zero_division=0
    )

    f1_weighted = f1_score(
        true_labels,
        predictions,
        average="weighted",
        zero_division=0
    )

    # --------------------------------------------------------
    # MCC
    # --------------------------------------------------------

    mcc = matthews_corrcoef(
        true_labels,
        predictions
    )

    # --------------------------------------------------------
    # Cohen's Kappa
    # --------------------------------------------------------

    kappa = cohen_kappa_score(
        true_labels,
        predictions
    )

    # --------------------------------------------------------
    # Print metrics
    # --------------------------------------------------------

    print(
        f"\nAccuracy              : {accuracy:.4f}"
    )

    print(
        f"Macro Precision       : {precision_macro:.4f}"
    )

    print(
        f"Weighted Precision    : {precision_weighted:.4f}"
    )

    print(
        f"Macro Recall          : {recall_macro:.4f}"
    )

    print(
        f"Weighted Recall       : {recall_weighted:.4f}"
    )

    print(
        f"Macro F1-Score        : {f1_macro:.4f}"
    )

    print(
        f"Weighted F1-Score     : {f1_weighted:.4f}"
    )

    print(
        f"Matthews Corr. Coef.  : {mcc:.4f}"
    )

    print(
        f"Cohen's Kappa         : {kappa:.4f}"
    )

    # --------------------------------------------------------
    # Classification report
    # --------------------------------------------------------

    print("\n" + "-" * 70)
    print("PER-CLASS CLASSIFICATION REPORT")
    print("-" * 70)

    report = classification_report(
        true_labels,
        predictions,
        target_names=[
            "Glioma",
            "No Tumor",
            "Pituitary",
            "Meningioma"
        ],
        digits=4,
        zero_division=0
    )

    print(report)

    # Save report
    with open(
        os.path.join(
            OUTPUT_DIR,
            "classification_report.txt"
        ),
        "w"
    ) as f:

        f.write(
            "BRAIN TUMOR CLASSIFICATION REPORT\n"
        )

        f.write(
            "=" * 70 + "\n\n"
        )

        f.write(
            f"Accuracy              : {accuracy:.4f}\n"
        )

        f.write(
            f"Macro Precision       : {precision_macro:.4f}\n"
        )

        f.write(
            f"Weighted Precision    : {precision_weighted:.4f}\n"
        )

        f.write(
            f"Macro Recall          : {recall_macro:.4f}\n"
        )

        f.write(
            f"Weighted Recall       : {recall_weighted:.4f}\n"
        )

        f.write(
            f"Macro F1-Score        : {f1_macro:.4f}\n"
        )

        f.write(
            f"Weighted F1-Score     : {f1_weighted:.4f}\n"
        )

        f.write(
            f"Matthews Corr. Coef.  : {mcc:.4f}\n"
        )

        f.write(
            f"Cohen's Kappa         : {kappa:.4f}\n\n"
        )

        f.write(
            report
        )

    return {
        "accuracy": accuracy,
        "macro_precision": precision_macro,
        "weighted_precision": precision_weighted,
        "macro_recall": recall_macro,
        "weighted_recall": recall_weighted,
        "macro_f1": f1_macro,
        "weighted_f1": f1_weighted,
        "mcc": mcc,
        "cohen_kappa": kappa
    }


