# 11. PER-CLASS SPECIFICITY
# ============================================================

def calculate_specificity(
    true_labels,
    predictions
):

    cm = confusion_matrix(
        true_labels,
        predictions
    )

    specificities = {}

    for i, class_name in enumerate(
        CLASS_NAMES
    ):

        true_positive = cm[i, i]

        false_positive = (
            cm[:, i].sum() - true_positive
        )

        false_negative = (
            cm[i, :].sum() - true_positive
        )

        true_negative = (
            cm.sum()
            - true_positive
            - false_positive
            - false_negative
        )

        if (
            true_negative + false_positive
        ) == 0:

            specificity = 0.0

        else:

            specificity = (
                true_negative
                /
                (
                    true_negative
                    + false_positive
                )
            )

        specificities[class_name] = specificity

    print("\n" + "-" * 70)
    print("PER-CLASS SPECIFICITY")
    print("-" * 70)

    for class_name, value in specificities.items():

        print(
            f"{class_name:15s}: {value:.4f}"
        )

    # Save
    with open(
        os.path.join(
            OUTPUT_DIR,
            "specificity.txt"
        ),
        "w"
    ) as f:

        f.write(
            "Per-Class Specificity\n"
        )

        f.write(
            "=" * 40 + "\n"
        )

        for class_name, value in specificities.items():

            f.write(
                f"{class_name}: {value:.4f}\n"
            )

    return specificities


