"""
Brain Tumor Detection - 4 Class CNN
====================================

Classes:
    0 = Glioma
    1 = No Tumor
    2 = Pituitary
    3 = Meningioma

Dataset:
    Training:
        Glioma       = 1400
        No Tumor     = 1400
        Pituitary    = 1400
        Meningioma   = 1400
        Total        = 5600

    Testing:
        Glioma       = 400
        No Tumor     = 400
        Pituitary    = 400
        Meningioma   = 400
        Total        = 1600

IMPORTANT:
    - Training is performed ONLY on training/ (with a validation split
      carved out of it -- see FIX #1 below)
    - Final evaluation is performed ONLY on testing/
    - Training images are NOT used for final prediction/evaluation
    - No external/demo images are downloaded

--- FIXES vs. the original version ---------------------------------------

FIX #1 - CRITICAL BUG: model.fit() was called with callbacks monitoring
    "val_loss"/"val_accuracy" (EarlyStopping, ReduceLROnPlateau,
    ModelCheckpoint) but NO validation_data was ever passed in. Keras does
    not error on this -- it silently skips those callbacks entirely, since
    there is nothing for them to monitor. In practice this meant:
      - EarlyStopping never triggered -> trained the full 30 epochs
        regardless of overfitting
      - ReduceLROnPlateau never fired -> learning rate never adapted
      - ModelCheckpoint never saved a "best" model -> the fully-trained,
        unregularized model was what got evaluated
    Fixed by using ImageDataGenerator(validation_split=...) with
    flow_from_directory(subset="training"/"validation"), carving a real
    validation set out of the training folder while keeping testing/
    completely untouched for final evaluation, and passing that
    validation generator into model.fit().

FIX #2 - Transfer learning (EfficientNetB0, ImageNet weights) instead of a
    from-scratch CNN. With no working validation signal, the original
    model overfit toward the "easy" classes (Glioma/No Tumor/Pituitary,
    which separate cleanly) while never being corrected on the harder
    Meningioma-vs-Glioma boundary. A pretrained backbone starts with much
    stronger general visual features, which typically helps most on
    exactly this kind of fine-grained, hard-to-separate class pair.

FIX #3 - Two-phase training: (a) frozen backbone, train new classifier
    head only; (b) unfreeze top backbone layers, fine-tune at a much
    lower learning rate. Both phases now have real EarlyStopping /
    ReduceLROnPlateau / ModelCheckpoint behavior since validation_data is
    correctly supplied throughout.

NOTE ON DATA QUALITY: this folder layout (glioma/notumor/pituitary/
    meningioma, 1400 each) matches a well-known public Kaggle brain-tumor
    MRI dataset. Users of that dataset have repeatedly reported
    Meningioma being the hardest class to separate from Glioma, including
    some images flagged as ambiguous/mislabeled in community discussion.
    If accuracy on Meningioma is still weak after these fixes, it's worth
    opening test_predictions.csv (already generated by this script),
    filtering to actual_class == "meningioma" with predicted_class ==
    "glioma", and visually spot-checking a handful of those MRI slices
    yourself -- that's the fastest way to tell "model needs more
    work" apart from "some of these images are genuinely
    ambiguous/mislabeled."
"""

